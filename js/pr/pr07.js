// Діагностика стосується лише неправильних полів: правильні числові поля приховуємо від правил,
// щоб випадковий збіг з «типовою помилкою» не давав хибної поради.
for (const T of P.tasks) {
  const diag = T.diagnose;
  T.diagnose = (p, v) => {
    const w = { ...v };
    for (const fl of T.fields(p)) if (fl.type !== "choice") w[fl.id] = checkField(fl, v[fl.id]) ? NaN : num(v[fl.id]);
    return diag(p, w);
  };
}
